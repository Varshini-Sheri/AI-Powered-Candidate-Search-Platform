// Writes .env.local from the running local Supabase stack, so the only values
// that come from outside are the model key and STRIPE_WEBHOOK_SECRET.
// Only the Supabase keys are managed here: any other line already in .env.local
// (a GEMINI_API_KEY or STRIPE_WEBHOOK_SECRET added before `make setup`, comments)
// is kept, so running setup never wipes a key someone put there.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const out = execFileSync("npx", ["--no-install", "supabase", "status", "-o", "env"], { encoding: "utf8" });
const vars: Record<string, string> = {};
for (const line of out.split("\n")) {
  const m = line.match(/^([A-Z_]+)="?(.*?)"?$/);
  if (m) vars[m[1]] = m[2];
}

const url = vars.API_URL;
const publishable = vars.PUBLISHABLE_KEY ?? vars.ANON_KEY;
const secret = vars.SECRET_KEY ?? vars.SERVICE_ROLE_KEY;
if (!url || !publishable || !secret) {
  console.error("Could not read API_URL and keys from `supabase status -o env`. Output was:\n" + out);
  process.exit(1);
}

const HEADER = "# Generated by `npm run env:write` from the local Supabase stack. Do not commit.";
const managed: Record<string, string> = {
  NEXT_PUBLIC_SUPABASE_URL: url,
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: publishable,
  SUPABASE_SECRET_KEY: secret,
};

// Keep every existing line except our header and the keys we manage.
const keyOf = (line: string) => line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/)?.[1];
const previous = existsSync(".env.local") ? readFileSync(".env.local", "utf8").split(/\r?\n/) : [];
const kept = previous.filter((line) => line !== HEADER && !(keyOf(line) && keyOf(line)! in managed) && line.trim() !== "");

writeFileSync(
  ".env.local",
  [HEADER, ...Object.entries(managed).map(([k, v]) => `${k}=${v}`), ...kept, ""].join("\n"),
);
const others = kept.filter((line) => keyOf(line)).length;
console.log(`Wrote .env.local${others ? ` (kept ${others} other setting${others === 1 ? "" : "s"})` : ""}`);